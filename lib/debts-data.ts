export function loadDebtsStore(): DebtsFullStore {
  const fallback = getInitialDebtsStore();
  if (typeof window === 'undefined') return fallback;
  try {
    const raw = localStorage.getItem(DEBTS_STORE_STORAGE_KEY);
    if (!raw) return fallback;
    const parsed = JSON.parse(raw) as Partial<DebtsFullStore>;
    return {
      debts: Array.isArray(parsed.debts) ? parsed.debts : fallback.debts,
      items: Array.isArray(parsed.items) ? parsed.items : fallback.items,
      payments: Array.isArray(parsed.payments) ? parsed.payments : fallback.payments,
      schedules: Array.isArray(parsed.schedules) ? parsed.schedules : fallback.schedules,
      installments: Array.isArray(parsed.installments) ? parsed.installments : fallback.installments,
      followups: Array.isArray(parsed.followups) ? parsed.followups : fallback.followups,
      settlements: Array.isArray(parsed.settlements) ? parsed.settlements : fallback.settlements,
      violations: Array.isArray(parsed.violations) ? parsed.violations : fallback.violations,
      appeals: Array.isArray(parsed.appeals) ? parsed.appeals : fallback.appeals,
      rules: Array.isArray(parsed.rules) && parsed.rules.length ? parsed.rules : fallback.rules,
      legalVersions: Array.isArray(parsed.legalVersions) && parsed.legalVersions.length ? parsed.legalVersions : fallback.legalVersions,
      auditLogs: Array.isArray(parsed.auditLogs) ? parsed.auditLogs : fallback.auditLogs,
      settings: parsed.settings ? { ...fallback.settings, ...parsed.settings } : fallback.settings,
    };
  } catch {
    return fallback;
  }
}

export function saveDebtsStore(store: DebtsFullStore): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(DEBTS_STORE_STORAGE_KEY, JSON.stringify(store));
  } catch {
    // Ignore quota limits cleanly
  }
}

/**
 * تصدير CSV عربي متوافق مع Excel بترميز UTF-8 BOM
 */
export function exportCsvUtf8Bom(filename: string, headers: string[], rows: (string | number)[][]): void {
  if (typeof window === 'undefined') return;
  const escapeCell = (cell: string | number) => {
    const str = String(cell ?? '').replace(/"/g, '""');
    return `"${str}"`;
  };
  const csvLines = [headers.map(escapeCell).join(','), ...rows.map((r) => r.map(escapeCell).join(','))];
  const blob = new Blob(['\uFEFF' + csvLines.join('\r\n')], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
